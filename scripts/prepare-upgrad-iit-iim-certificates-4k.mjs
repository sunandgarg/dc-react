#!/usr/bin/env node

import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const repoRoot = process.cwd();
const syncRoot = path.resolve(repoRoot, "../upgrad-sync");
const manifestPath = path.join(syncRoot, "prepared-media-manifest.json");
const outputDirectory = path.join(repoRoot, "public/assets/programs/iit-iim/certificates");
const outputMapPath = path.join(repoRoot, "src/lib/upgradProgramCertificateMedia.generated.ts");
const IIT_IIM_PATTERN = /(?:^|[^a-z0-9])(?:iiit|iit|iim)(?=$|[^a-z0-9])/i;
const ALLOWED_UPGRAD_HOSTS = new Set(["upgrad.com", "www.upgrad.com"]);

function digest(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

function isUpgradSource(sourceUrl) {
  const host = new URL(sourceUrl).hostname.toLowerCase();
  return ALLOWED_UPGRAD_HOSTS.has(host) || host.endsWith(".upgrad.com") || host.endsWith(".cloudfront.net");
}

function isIitIimProgramme(programme) {
  return [programme.slug, programme.title, programme.college_name]
    .filter((value) => typeof value === "string")
    .some((value) => IIT_IIM_PATTERN.test(value));
}

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
if (!Array.isArray(manifest)) throw new Error("Prepared upGrad media manifest must be an array");

await mkdir(outputDirectory, { recursive: true });
const media = {};
for (const programme of manifest.filter(isIitIimProgramme).sort((left, right) => left.slug.localeCompare(right.slug))) {
  const asset = programme.assets?.certificate;
  if (!asset?.output_path || !asset?.source_url) continue;
  if (!isUpgradSource(asset.source_url)) throw new Error(`Rejected non-upGrad certificate source for ${programme.slug}: ${asset.source_url}`);

  const input = await readFile(asset.output_path);
  const inputImage = sharp(input, { failOn: "warning", limitInputPixels: 100_000_000 }).rotate();
  const inputMetadata = await inputImage.metadata();
  const { data: output, info } = await inputImage
    .resize({ width: 3840, height: 3840, fit: "inside", withoutEnlargement: false, kernel: sharp.kernel.lanczos3 })
    .webp({ quality: 95, smartSubsample: true, effort: 6 })
    .toBuffer({ resolveWithObject: true });
  const outputSha = digest(output);
  const filename = `certificate-${outputSha.slice(0, 20)}.webp`;
  await writeFile(path.join(outputDirectory, filename), output);
  media[programme.slug] = {
    certificateImage: `/assets/programs/iit-iim/certificates/${filename}`,
    sourceUrl: asset.source_url,
    sourceWidth: Number(inputMetadata.width || 0),
    sourceHeight: Number(inputMetadata.height || 0),
    width: info.width,
    height: info.height,
    sha256: outputSha,
  };
}

const lines = [
  "/**",
  " * AUTO-GENERATED by scripts/prepare-upgrad-iit-iim-certificates-4k.mjs.",
  " * Source artwork is restricted to the audited upGrad media manifest.",
  " */",
  "export type UpgradProgramCertificateMedia = Readonly<{",
  "  certificateImage: string;",
  "  sourceUrl: string;",
  "  sourceWidth: number;",
  "  sourceHeight: number;",
  "  width: number;",
  "  height: number;",
  "  sha256: string;",
  "}>;",
  "",
  "export const UPGRAD_PROGRAM_CERTIFICATE_MEDIA = ",
  `${JSON.stringify(media, null, 2)} as const satisfies Readonly<Record<string, UpgradProgramCertificateMedia>>;`,
  "",
];
await writeFile(outputMapPath, lines.join("\n"), "utf8");
console.log(JSON.stringify({ programmes: Object.keys(media).length, outputDirectory, outputMapPath }, null, 2));
